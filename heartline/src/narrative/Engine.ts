import { formatClock } from '../core/time';
import { labReport } from '../medical/Patient';
import { PATIENT_ID, type GameState } from '../state/GameState';
import type { Lang, LText } from '../state/types';
import type { Choice, Dialogue, Line, Node } from './types';

export interface EngineHooks {
  /** Director actions such as 'scene:car' or 'leaveBed'. */
  action?(name: string): void;
  /** Called whenever the visible dialogue state changes. */
  update?(): void;
  /** Called when a dialogue ends. */
  end?(dialogueId: string): void;
}

/** A shown line, already resolved for conditions. */
export interface ShownLine extends Line {
  /** True for results generated by actions (echo findings, lab results). */
  result?: boolean;
}

/**
 * Runs data-driven dialogues. It knows nothing about rendering: UI reads `line`, `choices` and
 * calls `next()` / `choose()`. All state changes go through GameState.apply().
 */
export class NarrativeEngine {
  dialogue: Dialogue | null = null;
  node: Node | null = null;
  private queue: ShownLine[] = [];
  line: ShownLine | null = null;

  constructor(
    private state: GameState,
    private library: Record<string, Dialogue>,
    private hooks: EngineHooks = {},
  ) {}

  get active() {
    return !!this.dialogue;
  }

  start(id: string, nodeId?: string) {
    const d = this.library[id];
    if (!d) throw new Error(`Unknown dialogue ${id}`);
    this.dialogue = d;
    this.enter(nodeId ?? d.start);
  }

  private enter(nodeId: string | null | undefined): void {
    if (!this.dialogue) return;
    if (!nodeId) return this.finish();
    const n = this.dialogue.nodes[nodeId];
    if (!n) throw new Error(`Unknown node ${this.dialogue.id}.${nodeId}`);
    if (n.redirect) {
      for (const r of n.redirect) if (this.state.check(r.cond)) return this.enter(r.to);
    }
    this.node = n;
    this.state.data.node = `${this.dialogue.id}.${n.id}`;
    const results = this.state.apply(n.onEnter, this.dialogue.id);
    this.queue = (n.lines ?? []).filter((l) => this.state.check(l.cond)).map((l) => ({ ...l }));
    for (const r of results) this.queue.push({ speaker: null, text: r, result: true });
    // Nodes with choices fire their action on entry; otherwise it fires once the lines are read.
    if (n.action && n.choices?.length) {
      this.hooks.action?.(n.action);
      if (this.node !== n) return;
    }
    this.line = this.queue.shift() ?? null;
    if (!this.line && !this.visibleChoices().length) return this.after();
    this.hooks.update?.();
  }

  /** Advance to the next line, or to the next node when lines are exhausted and there are no choices. */
  next() {
    if (!this.node) return;
    if (this.queue.length) {
      this.line = this.queue.shift()!;
      this.hooks.update?.();
      return;
    }
    if (this.visibleChoices().length) {
      if (this.line) {
        this.line = null;
        this.hooks.update?.();
      }
      return;
    }
    this.after();
  }

  private after() {
    const n = this.node;
    if (!n) return;
    this.line = null;
    if (n.action && !n.choices?.length) {
      this.hooks.action?.(n.action);
      // The action may have started another dialogue or ended this one.
      if (this.node !== n) return;
    }
    this.enter(n.next ?? null);
  }

  /** Whether the player is currently looking at choices. */
  get choosing() {
    return !!this.node && !this.line && this.visibleChoices().length > 0;
  }

  visibleChoices(): Choice[] {
    return (this.node?.choices ?? []).filter((c) => this.state.check(c.showIf));
  }

  isLocked(c: Choice) {
    return !this.state.check(c.cond);
  }

  choose(choiceId: string) {
    if (!this.node || !this.dialogue) return;
    const c = this.visibleChoices().find((x) => x.id === choiceId);
    if (!c || this.isLocked(c)) return;
    const from = this.dialogue.id;
    this.state.data.flags[`chose:${from}.${this.node.id}`] = c.id;
    const results = this.state.apply(c.effects, from);
    if (c.action) this.hooks.action?.(c.action);
    if (this.dialogue?.id !== from) return;
    if (results.length) {
      // Show results first, then continue to the next node.
      const target = c.next;
      this.node = { id: '__result', lines: [], next: target };
      this.queue = results.map((r) => ({ speaker: null, text: r, result: true }));
      this.line = this.queue.shift()!;
      this.hooks.update?.();
      return;
    }
    this.enter(c.next);
  }

  /** Timer ran out: take the node's timeout choice (or the first unlocked one). */
  timeout() {
    if (!this.choosing || !this.node) return;
    const cs = this.visibleChoices().filter((c) => !this.isLocked(c));
    const pick = cs.find((c) => c.id === this.node!.timeoutChoice) ?? cs[cs.length - 1];
    if (pick) {
      this.state.apply({ stats: { stress: 4 }, history: { text: { tr: 'Karar süresi doldu; tereddüt bir karara dönüştü.', en: 'Time ran out; hesitation became a decision.' }, tag: 'self' } });
      this.choose(pick.id);
    }
  }

  /** Decision timer adjusted by stress: high stress means less time to think. */
  timerFor(n: Node): number {
    if (!n.timer) return 0;
    const stress = this.state.stat('stress');
    return Math.max(6, n.timer * (1.25 - stress / 160));
  }

  private finish() {
    const id = this.dialogue?.id ?? '';
    this.dialogue = null;
    this.node = null;
    this.line = null;
    this.queue = [];
    this.state.data.node = null;
    this.hooks.update?.();
    this.hooks.end?.(id);
  }

  /** Abort without running end hooks' side effects beyond clearing state (used on load). */
  reset() {
    this.dialogue = null;
    this.node = null;
    this.line = null;
    this.queue = [];
  }

  text(t: LText, lang: Lang): string {
    return interpolate(t[lang], this.state, lang);
  }
}

/** Replace {tokens} with live values from the game state. */
export function interpolate(s: string, state: GameState, lang: Lang): string {
  if (!s.includes('{')) return s;
  const p = state.patient(PATIENT_ID);
  const map: Record<string, string> = {
    time: formatClock(state.clock),
    map: String(p.map),
    hr: String(p.hr),
    cvp: String(p.cvp),
    drain: String(p.drainRate),
    drainTotal: String(Math.round(p.drainTotal)),
    hb: p.hb.toFixed(1),
    lactate: p.lactate.toFixed(1),
    temp: p.temp.toFixed(1),
    labs: labReport(p)[lang],
    sinceCall: String(Math.max(0, Math.round(state.clock - p.callAt))),
  };
  return s.replace(/\{(\w+)\}/g, (m, k: string) => map[k] ?? m);
}
